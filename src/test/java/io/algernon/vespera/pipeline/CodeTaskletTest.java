    @Test
    @Story("A reference page a documentation generator wrote is kept as code")
    @DisplayName("A mark is found in a page's first or last 64 KB, in single-byte text too, and not between them nor in bytes that do not read as text")
    void aMarkIsLookedForInTheFirstAndTheLast64KbOfTextOnly(@TempDir Path root, @TempDir Path workingDirectory)
            throws Exception {
        String haddockFooter = "<div id=\"footer\"><p>Produced by <a href=\"http://www.haskell.org/haddock/\">Haddock</a>"
                + " version 2.29.1</p></div></body></html>\n";
        String javadocMark = "<!-- Generated by javadoc (17) -->\n";
        Files.writeString(root.resolve("Data-Maybe.html"), pageOfSize(
                OVER_TWO_WINDOWS, "<html><head><title>Data.Maybe</title></head><body>\n", "", haddockFooter));
        Files.writeString(root.resolve("String.html"), pageOfSize(
                OVER_TWO_WINDOWS + 1, "<html><head><title>String</title></head><body>\n", javadocMark, "</body></html>\n"));
        Files.write(root.resolve("Widget.html"), singleByteText(
                "<html><head>\n" + javadocMark + "<title>Widget (perchè)</title></head><body><h1>Widget</h1></body></html>\n"));
        byte[] withANul = ("<html><head>\n" + javadocMark + "<title>Gadget</title></head><body>\u0000</body></html>\n")
                .getBytes(StandardCharsets.US_ASCII);
        Files.write(root.resolve("Gadget.html"), withANul);
        Ledger ledger = new Ledger(jdbcTemplate);
        WalkId walkId = walkRecorder(ledger).walk(root);

        stageOne(ledger, root, workingDirectory);

        claim(
                "a page whose only mark is its footer, in its last 64 KB, is code",
                () -> assertThat(verdictReasonsFor(ledger, walkId, "Data-Maybe.html"))
                        .containsExactly(MARK_REASON.formatted("Haddock")));
        claim(
                "a page whose only mark lies between its first and its last 64 KB is not: that stretch is not read",
                () -> assertThat(verdictKindsFor(ledger, walkId, "String.html")).isEmpty());
        claim(
                "a page in a single-byte encoding, of no known kind, that reads as text and carries a mark is code",
                () -> {
                    assertThat(storedFormatOf(ledger, walkId, "Widget.html")).isEqualTo("UNRECOGNISED");
                    assertThat(verdictReasonsFor(ledger, walkId, "Widget.html")).containsExactly(MARK_REASON.formatted("Javadoc"));
                });
        claim(
                "a page carrying a mark and a byte of nought is not: marks are looked for only in what reads as text",
                () -> assertThat(verdictKindsFor(ledger, walkId, "Gadget.html")).isEmpty());
    }


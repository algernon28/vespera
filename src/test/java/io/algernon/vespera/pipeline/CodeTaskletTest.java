    /** Writes each page as {@code <prefix>-<n>.html}, with a length of its own, and returns the names in order. */
    private static List<String> writeEach(Path root, String prefix, Map<String, String> pages) throws IOException {
        List<String> names = new ArrayList<>();
        int n = 0;
        for (String text : pages.values()) {
            n++;
            String name = prefix + "-" + n + ".html";
            // a comment of a length of its own, so that no two pages share a size
            Files.writeString(root.resolve(name), text + "<!--" + "-".repeat(n) + "-->\n");
            names.add(name);
        }
        return names;
    }

    /** A small HTML page: {@code head} inside its head, {@code body} and {@code footer} inside its body. */
    private static String page(String head, String body, String footer) {
        return "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n" + head + "\n</head>\n<body>\n"
                + body + "\n" + footer + "\n</body>\n</html>\n";
    }

    /**
     * A page of exactly {@code size} bytes: {@code head}, lines of prose, {@code middle} at {@link #BETWEEN_THE_WINDOWS}
     * where it is not empty, more prose, and {@code tail} at its very end.
     */
    private static String pageOfSize(int size, String head, String middle, String tail) {
        StringBuilder text = new StringBuilder(head);
        if (!middle.isEmpty()) {
            text.append(prose(BETWEEN_THE_WINDOWS - text.length())).append(middle);
        }
        text.append(prose(size - text.length() - tail.length())).append(tail);
        return text.toString();
    }

    /** Lines of ASCII prose, exactly {@code length} characters long. */
    private static String prose(int length) {
        StringBuilder text = new StringBuilder();
        int line = 0;
        while (text.length() < length) {
            text.append("<p>A line of the page, number ").append(line++).append(".</p>\n");
        }
        text.setLength(length);
        if (length > 0) {
            text.setCharAt(length - 1, '\n');
        }
        return text.toString();
    }

    /** ASCII text of exactly {@code size} bytes holding {@code b} at {@code at}. */
    private static byte[] textWithAByteAt(int size, int at, byte b) {
        byte[] bytes = prose(size).getBytes(StandardCharsets.US_ASCII);
        bytes[at] = b;
        return bytes;
    }

    /** {@code text} in ISO 8859-1, so that a letter such as {@code è} is one byte UTF-8 never follows with a space. */
    private static byte[] singleByteText(String text) {
        return text.getBytes(StandardCharsets.ISO_8859_1);
    }

    /** {@link #LOG_LINES} lines, each beginning with a timestamp of its own. */
    private static String timestampedLines(String what) {
        StringBuilder log = new StringBuilder();
        for (int line = 0; line < LOG_LINES; line++) {
            log.append("[2023-02-08 12:00:").append(String.format(Locale.ROOT, "%02d", line))
                    .append(",096] DEBUG -- a transaction was ").append(what).append('\n');
        }
        return log.toString();
    }

    /** The eight bytes every PNG begins with, then enough to give it a length of its own. */
    private static final byte[] PNG_FILE = {
        (byte) 0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n', 0, 0, 0, 0x0D, 'I', 'H', 'D', 'R', 0, 0, 0, 1, 0, 0, 0, 1
    };

    /** The page from {@code heading} to the next heading of the same level, or nothing where it has no such heading. */
    private static String section(String html, String heading) {
        int from = html.indexOf(heading);
        if (from < 0) {
            return "";
        }
        int to = html.indexOf("<h2>", from + heading.length());
        return to < 0 ? html.substring(from) : html.substring(from, to);
    }

    /** The count the page prints on the line for {@code label}. */
    private static int countIn(String html, String label) {
        Matcher matcher = Pattern.compile(Pattern.quote(label) + "[^0-9]{0,80}?([0-9]+)").matcher(html);
        if (!matcher.find()) {
            throw new IllegalStateException("the page has no line for " + label + ": " + html);
        }
        return Integer.parseInt(matcher.group(1));
    }


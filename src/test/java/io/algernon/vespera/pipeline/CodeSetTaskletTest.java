    @Test
    @Story("A code set's build files stay with it")
    @DisplayName("Each listed build file in a code set, matched in any case or by its ending, is kept as code with its set and never hashed; names left off the list stay documents")
    void aBuildFileInASetIsKeptAsCodeWithIt(@TempDir Path temp, @TempDir Path workingDirectory) throws Exception {
        Path root = namedRoot(temp);
        String setupCfg = "[metadata]\nname = rete\n";
        write(root, "cli/MAKEFILE", "all:\n\tcc -o cli main.c\n");
        write(root, "cli/main.c", "int main(void) { return 0; }\n");
        write(root, "cli/DESCRIPTION", text("cli/DESCRIPTION"));
        write(root, "cli/Doxyfile", text("cli/Doxyfile"));
        write(root, "cli/app.pro", text("cli/app.pro"));
        write(root, "cli/Makefile.am", text("cli/Makefile.am"));
        write(root, "net/Rete.SLN", "Microsoft Visual Studio Solution File, Format Version 12.00\n");
        write(root, "net/Rete.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>\n");
        write(root, "net/Program.java", "class Program {}\n");
        write(root, "net/setup.cfg", setupCfg);
        write(root, "ui/setup.cfg", setupCfg);
        write(root, "ui/ui.py", "print('ui')\n");

        List<String> logged = stageOneLogging(root, workingDirectory);

        List<String> buildFiles = List.of("cli/MAKEFILE", "net/Rete.SLN", "net/Rete.csproj", "net/setup.cfg", "ui/setup.cfg");
        for (String buildFile : buildFiles) {
            claim(
                    buildFile + " is kept as code, with the reason that it is a build file kept with its set",
                    () -> assertThat(verdictReasonsFor(buildFile)).containsExactly(BUILD_FILE_REASON));
        }
        claim(
                "each is a member of its own folder's set as a build file",
                () -> assertThat(List.of(
                                membershipOf("cli/MAKEFILE"),
                                membershipOf("net/Rete.SLN"),
                                membershipOf("net/Rete.csproj"),
                                membershipOf("net/setup.cfg"),
                                membershipOf("ui/setup.cfg")))
                        .containsExactly(
                                List.of("build-file in 'cli'"),
                                List.of("build-file in 'net'"),
                                List.of("build-file in 'net'"),
                                List.of("build-file in 'net'"),
                                List.of("build-file in 'ui'")));
        claim(
                "the two identical build files are both kept, never hashed, neither superseding the other",
                () -> {
                    assertThat(contentHashRowsFor("net/setup.cfg") + contentHashRowsFor("ui/setup.cfg")).isZero();
                    assertThat(jdbcTemplate.queryForObject("SELECT COUNT(*) FROM superseded_by", Integer.class)).isZero();
                });
        claim(
                "stage 1's log says of a build file that it is code, and why",
                () -> assertThat(logged).anyMatch(line -> line.endsWith("-> code: " + BUILD_FILE_REASON)));
        for (String notABuildFile : List.of("cli/DESCRIPTION", "cli/Doxyfile", "cli/app.pro", "cli/Makefile.am")) {
            claim(
                    notABuildFile + ", a name the list leaves out, is no member and carries no verdict",
                    () -> {
                        assertThat(membershipOf(notABuildFile)).isEmpty();
                        assertThat(verdictKindsFor(notABuildFile)).isEmpty();
                    });
        }
    }

    @Test
    @Story("A code set's build files stay with it")
    @DisplayName("A build file is one only where its bytes read as text: a binary file, a PDF or an empty file of a listed name marks no folder, and text in a single-byte encoding does")
    void aBuildFileIsOneOnlyWhereItsBytesReadAsText(@TempDir Path temp, @TempDir Path workingDirectory) throws Exception {
        Path root = namedRoot(temp);
        byte[] binary = new byte[64];
        for (int i = 0; i < binary.length; i++) {
            binary[i] = (byte) i;
        }
        write(root, "bin/x/Makefile", binary);
        write(root, "bin/x/y.c", "int y(void) { return 0; }\n");
        write(root, "pdf/x/package.json", pdf("pdf/x/package.json"));
        write(root, "pdf/x/z.c", "int z(void) { return 0; }\n");
        write(root, "vuoto/x/CMakeLists.txt", new byte[0]);
        write(root, "vuoto/x/w.c", "int w(void) { return 0; }\n");
        write(root, "latin/x/Makefile", "# compila tutto perchè\nall:\n\tcc -o l l.c\n".getBytes(StandardCharsets.ISO_8859_1));
        write(root, "latin/x/l.c", "int l(void) { return 0; }\n");

        stageOne(root, workingDirectory);

        claim(
                "only the build file whose bytes read as text marks its folder: the other three sets are below the first"
                        + " folder of their code",
                () -> assertThat(sets()).isEqualTo(Map.of("bin", "bin", "latin/x", "x", "pdf", "pdf", "vuoto", "vuoto")));
        claim(
                "the binary file and the PDF of a listed name are no members and carry no verdict, and the PDF is still"
                        + " a PDF",
                () -> {
                    assertThat(List.of(membershipOf("bin/x/Makefile"), membershipOf("pdf/x/package.json")))
                            .containsOnly(List.of());
                    assertThat(List.of(verdictKindsFor("bin/x/Makefile"), verdictKindsFor("pdf/x/package.json")))
                            .containsOnly(List.of());
                    assertThat(storedFormatOf("pdf/x/package.json")).isEqualTo("PDF");
                });
        claim(
                "the empty file of a listed name stays broken, and only broken",
                () -> assertThat(verdictKindsFor("vuoto/x/CMakeLists.txt")).containsExactly(BROKEN));
        claim(
                "the build file in a single-byte encoding, of no known kind, reads as text and is kept with its set",
                () -> {
                    assertThat(storedFormatOf("latin/x/Makefile")).isEqualTo("UNRECOGNISED");
                    assertThat(verdictKindsFor("latin/x/Makefile")).containsExactly(CODE);
                    assertThat(membershipOf("latin/x/Makefile")).containsExactly("build-file in 'latin/x'");
                });
    }


package io.algernon.vespera.corpus;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.channels.FileChannel;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Predicate;
import java.util.regex.Pattern;

/**
 * Which files stage 1 keeps as code (ADR-277): text written to be compiled or interpreted, recognised by a name
 * ending the profile's {@code codeNameEndings} lists, or a page of reference a documentation generator wrote,
 * recognised by its mark. Only a file detected {@code PLAIN_TEXT} or {@code UNRECOGNISED} is read for either rule
 * (section 3), and only where its first and last 64 KB read as text.
 *
 * <p>The generators' marks are built in here as the signatures of ADR-252 are, and a change to them is a new
 * {@link #MARKS_VERSION}, which stage 1 records among its configuration consumed (section 9).
 */
final class Code {

    private Code() {}

    /** The version of the list of generators' marks below (ADR-277 section 4); a change to it is a new version. */
    public static final String MARKS_VERSION = "v1";

    /** The two windows a file is read in, at its start and at its end (section 3). */
    private static final int WINDOW = TimestampedLines.WINDOW_BYTES;

    /** Each mark, normalised the first time it is looked for and not again for the next file. */
    private static final Map<String, String> NORMALISED_MARKS = new ConcurrentHashMap<>();

    /**
     * Why a file is code, and for which of the two rules: the ending of its name, as the list holds it, or a
     * generator's mark. Exactly one of {@code ending} and {@code generator} is present.
     */
    record Recognised(String reason, Optional<String> ending, Optional<String> generator) {}

    /**
     * Why {@code file} is code, or empty where it is not. The ending of its name is tried before a mark, so a file
     * both rules reach is code for its ending (section 6). {@code endings} are the profile's
     * {@code codeNameEndings}, lower case; none where the key is unset or unreadable.
     */
    static Optional<Recognised> reasonFor(Path file, DetectedFormat format, List<String> endings) throws IOException {
        if (format != DetectedFormat.PLAIN_TEXT && format != DetectedFormat.UNRECOGNISED) {
            return Optional.empty();
        }
        Optional<String> ending = matchingEnding(file, endings);
        Windows windows = Windows.of(file);
        if (!windows.readsAsText()) {
            return Optional.empty();
        }
        if (ending.isPresent()) {
            String name = file.getFileName().toString();
            return Optional.of(new Recognised(
                    "a file whose name ends with " + spelt(name, ending.get())
                            + ", an ending codeNameEndings in profile.yaml lists as code",
                    ending,
                    Optional.empty()));
        }
        return generatorOf(windows)
                .map(generator -> new Recognised("a reference page generated by " + generator, Optional.empty(), Optional.of(generator)));
    }

    /**
     * Whether the first and last 64 KB of {@code file} read as text (section 3), for a caller that asks it of a
     * file no rule of this class has judged: a set's build file or a generated tree's companion (ADR-284).
     */
    static boolean readsAsText(Path file) throws IOException {
        return Windows.of(file).readsAsText();
    }

    /**
     * The generator whose mark {@code file} carries, by section 4's test applied as the first pass applies it:
     * empty where its bytes do not read as text or no generator is named. Throws where it cannot be read.
     */
    static Optional<String> markOf(Path file) throws IOException {
        Windows windows = Windows.of(file);
        return windows.readsAsText() ? generatorOf(windows) : Optional.empty();
    }

    /** Whether {@code name} ends, in any case, with one of {@code endings}. */
    static boolean endsWithAny(String name, List<String> endings) {
        String folded = name.toLowerCase(Locale.ROOT);
        return endings.stream().anyMatch(ending -> folded.endsWith(ending.toLowerCase(Locale.ROOT)));
    }

    /**
     * Where {@code generator} comes in the order of section 4's tables, the first being 0: what settles a file
     * that lies in two generators' trees whose roots are one folder (ADR-284 section 5).
     */
    static int rankOf(String generator) {
        for (int rank = 0; rank < GENERATORS.size(); rank++) {
            if (GENERATORS.get(rank).name.equals(generator)) {
                return rank;
            }
        }
        throw new IllegalArgumentException("no generator is named " + generator);
    }

    /** The longest listed ending the file's name ends with, in any case. */
    private static Optional<String> matchingEnding(Path file, List<String> endings) {
        String folded = file.getFileName().toString().toLowerCase(Locale.ROOT);
        return endings.stream()
                .filter(ending -> folded.endsWith(ending.toLowerCase(Locale.ROOT)))
                .max(Comparator.comparingInt(String::length));
    }

    /**
     * The ending as the file's name spells it, or as listed where folding changed the name's length (the spelling
     * ADR-256 section 7 gives).
     */
    private static String spelt(String name, String ending) {
        int from = name.length() - ending.length();
        return from >= 0 && name.substring(from).toLowerCase(Locale.ROOT).equals(ending.toLowerCase(Locale.ROOT))
                ? name.substring(from)
                : ending;
    }

    /** The first generator, in the order of section 4's tables, whose mark and page-type check the windows satisfy. */
    private static Optional<String> generatorOf(Windows windows) {
        Page page = new Page(normalised(windows.first()), normalised(windows.last()));
        for (Generator generator : GENERATORS) {
            if (generator.test.test(page)) {
                return Optional.of(generator.name);
            }
        }
        return Optional.empty();
    }

    /**
     * What a file reads as: the bytes of its first and its last 64 KB, and whether the whole of what was read holds
     * text. A file of 128 KB or less is read whole, and between the two windows of a larger one nothing is read.
     */
    private record Windows(byte[] first, byte[] last, boolean readsAsText) {

        static Windows of(Path file) throws IOException {
            long size = Files.size(file);
            if (size <= TimestampedLines.WHOLE_FILE_LIMIT_BYTES) {
                byte[] whole = Files.readAllBytes(file);
                int window = Math.min(whole.length, WINDOW);
                return new Windows(
                        Arrays.copyOfRange(whole, 0, window),
                        Arrays.copyOfRange(whole, whole.length - window, whole.length),
                        holdsText(whole));
            }
            try (FileChannel channel = FileChannel.open(file, StandardOpenOption.READ)) {
                byte[] first = read(channel, 0);
                byte[] last = read(channel, size - WINDOW);
                return new Windows(first, last, holdsText(first) && holdsText(last));
            }
        }

        private static byte[] read(FileChannel channel, long from) throws IOException {
            ByteBuffer buffer = ByteBuffer.allocate(WINDOW);
            while (buffer.hasRemaining()) {
                int read = channel.read(buffer, from + buffer.position());
                if (read < 0) {
                    break;
                }
            }
            return Arrays.copyOf(buffer.array(), buffer.position());
        }

        /** No byte from {@code 00} to {@code 1F} but tab, line feed, form feed and carriage return (section 3). */
        private static boolean holdsText(byte[] bytes) {
            for (byte b : bytes) {
                int value = b & 0xFF;
                if (value < 0x20 && value != 0x09 && value != 0x0A && value != 0x0C && value != 0x0D) {
                    return false;
                }
            }
            return true;
        }
    }

    /**
     * Reads the bytes as ISO 8859-1, one character each, folds ASCII letters to lower case and makes each run of
     * spaces, tabs, line feeds, carriage returns and form feeds one space (section 4).
     */
    private static String normalised(byte[] bytes) {
        return normalised(new String(bytes, StandardCharsets.ISO_8859_1));
    }

    private static String normalised(String text) {
        StringBuilder out = new StringBuilder(text.length());
        boolean inSpace = false;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f') {
                if (!inSpace) {
                    out.append(' ');
                }
                inSpace = true;
            } else {
                inSpace = false;
                out.append(c >= 'A' && c <= 'Z' ? (char) (c + ('a' - 'A')) : c);
            }
        }
        return out.toString();
    }

    /** The two windows of a page, normalised; each string or pattern is looked for in each, never across them. */
    private record Page(String first, String last) {

        boolean has(String mark) {
            String wanted = NORMALISED_MARKS.computeIfAbsent(mark, Code::normalised);
            return first.contains(wanted) || last.contains(wanted);
        }

        boolean hasAny(String... marks) {
            for (String mark : marks) {
                if (has(mark)) {
                    return true;
                }
            }
            return false;
        }

        boolean matches(Pattern pattern) {
            return pattern.matcher(first).find() || pattern.matcher(last).find();
        }
    }

    private record Generator(String name, Predicate<Page> test) {}

    /** A generator that renders reference pages only: any one of the marks. */
    private static Generator reference(String name, String... marks) {
        return new Generator(name, page -> page.hasAny(marks));
    }

    /** A generator that also renders guides: a mark and, besides, the markup of a reference page. */
    private static Generator withGuides(String name, Predicate<Page> mark, Predicate<Page> referencePage) {
        return new Generator(name, page -> mark.test(page) && referencePage.test(page));
    }

    private static Predicate<Page> anyOf(String... marks) {
        return page -> page.hasAny(marks);
    }

    /** Doxygen's {@code Generated by} line in any language: a comment, a few words, the name, a version (section 4). */
    private static final Pattern DOXYGEN_COMMENT = Pattern.compile("<!-- [^<>]{1,40} doxygen [0-9][0-9.]* -->");

    /** Sandcastle's meta whose content opens a page: either name, any content. */
    private static final Pattern SANDCASTLE_META = Pattern.compile("<meta name=\"(microsoft\\.)?help\\.id\" content=\"");

    /** The same meta, whose content opens with the letter of a member of the reference (section 4). */
    private static final Pattern SANDCASTLE_REFERENCE_META = Pattern.compile(
            "<meta name=\"(microsoft\\.)?help\\.id\" content=\"(r:|n:|t:|m:|p:|f:|e:|overload:|allmembers\\.t:"
                    + "|methods\\.t:|properties\\.t:|events\\.t:|fields\\.t:|operators\\.t:)");

    /** Section 4's tables, in order: the generators of reference pages only, then those that also render guides. */
    private static final List<Generator> GENERATORS = List.of(
            reference("Javadoc", "<!-- Generated by javadoc", "<meta name=\"generator\" content=\"javadoc/"),
            reference("pdoc", "<meta name=\"generator\" content=\"pdoc"),
            reference("Haddock", "Produced by <a href=\"http://www.haskell.org/haddock/\""),
            reference(
                    "HeaderDoc",
                    "<meta name=\"generator\" content=\"HeaderDoc\"",
                    "HTML documentation generated by <a href=\"http://www.opensource.apple.com/projects\""),
            reference("ROBODoc", "<!-- Generated with ROBODoc Version", ">ROBODoc</a> V"),
            reference("Imagix 4D", "created by Imagix 4D -->"),
            reference("NDoc", "<body id=\"bodyID\" class=\"dtBODY\">"),
            reference("mkdocstrings", "class=\"doc doc-object doc-"),
            reference(
                    "phpDocumentor",
                    "Documentation is powered by <a href=\"http://www.phpdoc.org/\">phpDocumentor"),
            new Generator("pydoc", page -> page.has("<title>Python: ")
                    && page.hasAny("bgcolor=\"#7799ee\"", "class=\"heading-text decor\"", "<header class=\"heading\">")),
            withGuides(
                    "Doxygen",
                    page -> page.hasAny("<meta name=\"generator\" content=\"Doxygen ", "<!-- HTML header for doxygen ")
                            || page.matches(DOXYGEN_COMMENT),
                    page -> page.hasAny("class=\"memitem\"", "<table class=\"memberdecls\"")
                            || (page.has("<div class=\"fragment\">") && !page.has("<div class=\"textblock\">"))),
            withGuides(
                    "JSDoc",
                    anyOf("<title>JSDoc: ", "Documentation generated by <a href=\"https://github.com/jsdoc"),
                    anyOf(
                            "<title>JSDoc: Class: ",
                            "<title>JSDoc: Module: ",
                            "<title>JSDoc: Namespace: ",
                            "<title>JSDoc: Mixin: ",
                            "<title>JSDoc: External: ",
                            "<title>JSDoc: Interface: ",
                            "<title>JSDoc: Global",
                            "<title>JSDoc: Source: ",
                            "class=\"container-overview\"",
                            "<h4 class=\"name\" id=")),
            withGuides(
                    "YARD",
                    anyOf("title=\"Yay! A Ruby Documentation Tool\"", "&mdash; Documentation by YARD "),
                    anyOf("<div class=\"box_info\">", "class=\"method_details")),
            withGuides(
                    "RDoc",
                    anyOf(
                            "Generated by <a href=\"https://ruby.github.io/rdoc/\">RDoc",
                            "Generated by <a href=\"https://github.com/rdoc/rdoc\">RDoc",
                            "Based on <a href=\"http://deveiate.org/projects/Darkfish-RDoc/\">Darkfish",
                            "Generated with the <a href=\"http://deveiate.org/projects/Darkfish-Rdoc/\">Darkfish",
                            "rdoc-style.css"),
                    anyOf(
                            "<body id=\"top\" role=\"document\" class=\"class\">",
                            "<body id=\"top\" role=\"document\" class=\"module\">",
                            "class=\"class has-toc\"",
                            "id=\"classHeader\"")),
            withGuides(
                    "Natural Docs",
                    anyOf("<!-- Generated by Natural Docs, version ", "<html class=\"NDPage ND"),
                    anyOf("NDPrototype")),
            withGuides("Sandcastle", page -> page.matches(SANDCASTLE_META), page -> page.matches(SANDCASTLE_REFERENCE_META)
                    || page.has("<meta name=\"container\"")),
            withGuides(
                    "DocFX",
                    anyOf(
                            "<meta name=\"generator\" content=\"docfx ",
                            "<meta property=\"docfx:navrel\"",
                            "<meta name=\"docfx:navrel\"",
                            "Generated by <strong>DocFX</strong>",
                            "Made with <a href=\"https://dotnet.github.io/docfx\">docfx</a>"),
                    anyOf(
                            "data-yaml-mime=\"ManagedReference\"",
                            "data-yaml-mime=\"ApiPage\"",
                            "<div class=\"inheritance\">",
                            "_syntax\">Syntax</h5>")),
            withGuides(
                    "phpDocumentor",
                    anyOf("<!-- template designed by Marco Von Ballmoos -->", "<a href=\"http://www.phpdoc.org\">"),
                    anyOf("<h2 class=\"class-name\">", "<div class=\"method-signature\">")),
            withGuides(
                    "phpDocumentor",
                    anyOf("class=\"phpdocumentor-"),
                    anyOf(
                            "<article class=\"phpdocumentor-element -class",
                            "<article class=\"phpdocumentor-element -interface",
                            "<article class=\"phpdocumentor-element -trait",
                            "<article class=\"phpdocumentor-element -enum",
                            "phpdocumentor-signature")));
}
